IF NOT EXISTS ( SELECT 1 FROM CODELIST (NOLOCK) WHERE listname = 'PMDETTYPE' )
BEGIN
   INSERT INTO CODELIST (ListName, DESCRIPTION, Type)
   VALUES ('PMDETTYPE', 'Build Parameter Detail Type', 'DropDown')
END
ELSE
BEGIN
   UPDATE CODELIST WITH (ROWLOCK) 
   SET [Type] = 'DropDown'
   WHERE listname = 'PMDETTYPE'
   AND [Type] = ''
END

